from datetime import datetime
from pathlib import Path
import shutil
import sys

here = Path(__file__).resolve().parent
source = Path(sys.argv[1])
output = here.parent / 'settings/smali/system/priv-app/SecSettings/SecSettings.apk/0016-Add-ViPER-audio-controller.patch'
content = 'From: UN1CA <unica@local>\nSubject: [PATCH] Add ViPER audio controller\n\nGenerated by viper/build-controller.sh.\n\n'
files = sorted((source / 'io/mesalabs/unica/viper').glob('*.smali'))
if not files:
    raise SystemExit('Missing compiled controller')
for file in files:
    name = 'smali_classes4/' + file.relative_to(source).as_posix()
    lines = file.read_text().splitlines(keepends=True)
    content += f'diff --git a/{name} b/{name}\nnew file mode 100644\n--- /dev/null\n+++ b/{name}\n@@ -0,0 +1,{len(lines)} @@\n'
    content += ''.join('+' + line for line in lines) + '\n'
if output.exists() and output.read_text() != content:
    shutil.copy2(output, str(output) + '.bak.' + datetime.now().strftime('%Y%m%d_%H%M%S_%f'))
output.write_text(content)
print(output)
